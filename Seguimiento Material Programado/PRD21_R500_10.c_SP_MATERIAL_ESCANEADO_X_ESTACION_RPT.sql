				WHEN FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss') > 60001 AND FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss')  < 153001 THEN 1
				ELSE 2 END ) = 3
	GROUP BY  CONVERT( DATE, F_LOG)

	-- //////////SE MUESTRAN LOS TOTALES////////////////////////////////////////////////////
	SELECT	DIA.FECHA AS 'Fecha',
			ISNULL(TURNO_1.TOTAL_CAJAS, 0) AS '1er Turno',
			ISNULL(TURNO_2.TOTAL_CAJAS, 0) AS '2do Turno',
