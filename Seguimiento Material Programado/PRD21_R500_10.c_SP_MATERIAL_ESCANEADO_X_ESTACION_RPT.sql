*/

CREATE PROCEDURE [dbo].[PG_ESTACION_ESCANEO_CERTIFICACION_VS_LIBERACION_GRAF]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO_ACCION		INT,
	-- ===========================
	@PP_F_INICIAL				DATE,
	@PP_F_FIN					DATE
AS

	--///////// SE CREA TABLA TEMPORAL PARA GUARDAR LA INFORMACION //////////////// 
	DECLARE @TBL_MATERIAL_ESCANEADO_CERTIFICACION TABLE(
		FECHA		DATE,
		TOTAL_CAJAS	INT
	)
	 
	--///////// SE INGRESA LA INFORMACION DEL 1ER TURNO ////////////////
	INSERT INTO @TBL_MATERIAL_ESCANEADO_CERTIFICACION
	SELECT	CONVERT( DATE, F_LOG) AS FECHA,
			COUNT([K_MATERIAL_PROGRAMADO_LOG])
	FROM [MATERIAL_PROGRAMADO_LOG] (NOLOCK) 
	WHERE K_TIPO_EVENTO_KIT = 400 -- CERTIFICACION 
	AND CONVERT( DATE, F_LOG) >= @PP_F_INICIAL
	AND CONVERT( DATE, F_LOG) <= @PP_F_FIN
	GROUP BY  CONVERT( DATE, F_LOG)

	--///////// SE CREA TABLA TEMPORAL PARA GUARDAR LA INFORMACION //////////////// 
	DECLARE @TBL_MATERIAL_ESCANEADO_LIBERACION TABLE(
		FECHA		DATE,
		TOTAL_CAJAS	INT
	)
	 
	--///////// SE INGRESA LA INFORMACION DEL 1ER TURNO ////////////////
	INSERT INTO @TBL_MATERIAL_ESCANEADO_LIBERACION
	SELECT	CONVERT( DATE, F_LOG) AS FECHA,
			COUNT([K_MATERIAL_PROGRAMADO_LOG])
	FROM [MATERIAL_PROGRAMADO_LOG] (NOLOCK) 
	WHERE K_TIPO_EVENTO_KIT = 410 -- LIBERACION_QC 
	AND CONVERT( DATE, F_LOG) >= @PP_F_INICIAL
	AND CONVERT( DATE, F_LOG) <= @PP_F_FIN
	GROUP BY  CONVERT( DATE, F_LOG)


	-- //////////SE MUESTRAN LOS TOTALES////////////////////////////////////////////////////
	SELECT	CERTI.FECHA AS 'Fecha',
			ISNULL(CERTI.TOTAL_CAJAS, 0) AS 'Total Entrada',
			ISNULL(LIB.TOTAL_CAJAS, 0) AS 'Total Salida'
	FROM @TBL_MATERIAL_ESCANEADO_CERTIFICACION AS CERTI
	LEFT JOIN @TBL_MATERIAL_ESCANEADO_LIBERACION LIB ON CERTI.FECHA = LIB.FECHA
	ORDER BY CERTI.FECHA 
	-- //////////////////////////////////////////////////////////////
GO

