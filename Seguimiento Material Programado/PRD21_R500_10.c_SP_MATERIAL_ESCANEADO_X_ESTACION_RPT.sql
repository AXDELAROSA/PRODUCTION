CREATE PROCEDURE [dbo].[PG_ESTACION_ESCANEO_HEADER_RPT]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO_ACCION		INT, 
	-- ===========================
	@PP_ESTACION				INT,
	@PP_F_INICIAL				DATE,
	@PP_F_FIN					DATE,
	@PP_SECCION_DIA				INT
AS

	-- ///////////MATERIAL EN ESPERA DE SER LIBERADO POR CALIDAD/////////////////////////////////////
	DECLARE @VP_N_CAJAS INT = 0

	IF @PP_ESTACION = 400 -- #400 CERTIFICACION 
		BEGIN
			SELECT	@VP_N_CAJAS = COUNT([K_MATERIAL_PROGRAMADO])
			FROM [MATERIAL_PROGRAMADO] (NOLOCK) 
			WHERE K_TIPO_EVENTO_KIT IN ( 300, 400 ) --#300 INSP. PERF. #400 CERTIFICACION 

			IF @VP_N_CAJAS IS NULL
				SET @VP_N_CAJAS = 0
		END

	-- /////////SE MUESTRA EL RESULTADO//////////////
	SELECT	@PP_F_INICIAL	AS FECHA_INICIO,
			@PP_F_FIN		AS FECHA_FINAL,
			@PP_SECCION_DIA	AS SECCION_DIA,
			@VP_N_CAJAS		AS N_CAJAS
	
	-- ////////////////////////////////////////////////
	-- ////////////////////////////////////////////////
GO




