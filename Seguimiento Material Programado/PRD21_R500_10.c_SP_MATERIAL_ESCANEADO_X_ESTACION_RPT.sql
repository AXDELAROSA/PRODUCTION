	LEFT JOIN @TBL_MATERIAL_ESCANEADO_DEL_DIA_X_TURNO_2 TURNO_2 ON DIA.FECHA = TURNO_2.FECHA
	LEFT JOIN @TBL_MATERIAL_ESCANEADO_DEL_DIA_X_TURNO_3 TURNO_3 ON DIA.FECHA = TURNO_3.FECHA
	ORDER BY DIA.FECHA 
