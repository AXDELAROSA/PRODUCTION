*/

CREATE PROCEDURE [dbo].[PG_ESTACION_ESCANEO_X_DIA_MODELO_TURNO]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO_ACCION		INT,
	-- ===========================
	@PP_ESTACION				INT,
	@PP_F_INICIAL				DATE,
	@PP_F_FIN					DATE,
	@PP_TURNO					INT
AS

	SELECT	CONVERT( DATE, F_LOG) AS FECHA,
			LEFT(LTRIM(RTRIM(CHANGELEVEL)), 3) AS MODELO,
			COUNT([K_MATERIAL_PROGRAMADO_LOG]) AS N_CAJA
	FROM [MATERIAL_PROGRAMADO_LOG] (NOLOCK) 
	INNER JOIN ccjoblin_sql (NOLOCK) ON LTRIM(RTRIM(ccjoblin_sql.jobno)) + RIGHT('000'+ CONVERT(VARCHAR(5),ser_no), 3) = SERIAL
	WHERE K_TIPO_EVENTO_KIT = @PP_ESTACION 
	AND CONVERT( DATE, F_LOG) >= @PP_F_INICIAL
	AND CONVERT( DATE, F_LOG) <= @PP_F_FIN
	AND ( CASE WHEN FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss') > 0 AND FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss')  < 60002  THEN 3
				WHEN FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss') > 60001 AND FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss')  < 153001 THEN 1
				ELSE 2 END ) = @PP_TURNO 
	GROUP BY  CONVERT( DATE, F_LOG), LEFT(LTRIM(RTRIM(CHANGELEVEL)), 3)
	ORDER BY LEFT(LTRIM(RTRIM(CHANGELEVEL)), 3)
	
	-- //////////////////////////////////////////////////////////////
	-- //////////////////////////////////////////////////////////////
GO



