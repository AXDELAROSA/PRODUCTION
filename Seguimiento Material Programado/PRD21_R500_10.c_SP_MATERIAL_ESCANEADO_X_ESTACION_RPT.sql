	WHERE K_TIPO_EVENTO_KIT = @PP_ESTACION 
	AND CONVERT( DATE, F_LOG) >= @PP_F_INICIAL
	AND CONVERT( DATE, F_LOG) <= @PP_F_FIN
	GROUP BY  CONVERT( DATE, F_LOG)

	--///////// SE CREA TABLA TEMPORAL PARA GUARDAR LA INFORMACION ////////////////
	DECLARE @TBL_MATERIAL_ESCANEADO_DEL_DIA_X_TURNO_1 TABLE(
		FECHA		DATE,
		TOTAL_CAJAS	INT
	)
	 
	--///////// SE INGRESA LA INFORMACION DEL 1ER TURNO ////////////////
	INSERT INTO @TBL_MATERIAL_ESCANEADO_DEL_DIA_X_TURNO_1
	SELECT	CONVERT( DATE, F_LOG) AS FECHA,
			COUNT([K_MATERIAL_PROGRAMADO_LOG]) AS N_CAJA
	FROM [MATERIAL_PROGRAMADO_LOG] (NOLOCK) 
	WHERE K_TIPO_EVENTO_KIT = @PP_ESTACION 
	AND CONVERT( DATE, F_LOG) >= @PP_F_INICIAL
	AND CONVERT( DATE, F_LOG) <= @PP_F_FIN
	AND ( CASE WHEN FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss') > 0 AND FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss')  < 60002  THEN 3
				WHEN FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss') > 60001 AND FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss')  < 153001 THEN 1
				ELSE 2 END ) = 1
	GROUP BY  CONVERT( DATE, F_LOG)

	--///////// SE CREA TABLA TEMPORAL PARA GUARDAR LA INFORMACION ////////////////
	DECLARE @TBL_MATERIAL_ESCANEADO_DEL_DIA_X_TURNO_2 TABLE(
		FECHA		DATE,
		TOTAL_CAJAS	INT
	)
	 
	--///////// SE INGRESA LA INFORMACION DEL 2DO TURNO ////////////////
	INSERT INTO @TBL_MATERIAL_ESCANEADO_DEL_DIA_X_TURNO_2
	SELECT	CONVERT( DATE, F_LOG) AS FECHA,
			COUNT([K_MATERIAL_PROGRAMADO_LOG]) AS N_CAJA
	FROM [MATERIAL_PROGRAMADO_LOG] (NOLOCK) 
	WHERE K_TIPO_EVENTO_KIT = @PP_ESTACION 
	AND CONVERT( DATE, F_LOG) >= @PP_F_INICIAL
	AND CONVERT( DATE, F_LOG) <= @PP_F_FIN
	AND ( CASE WHEN FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss') > 0 AND FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss')  < 60002  THEN 3
				WHEN FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss') > 60001 AND FORMAT(CAST(F_LOG AS TIME(0)), N'hhmmss')  < 153001 THEN 1
				ELSE 2 END ) = 2
	GROUP BY  CONVERT( DATE, F_LOG)

	--///////// SE CREA TABLA TEMPORAL PARA GUARDAR LA INFORMACION ////////////////
