IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[PG_CB_KIT_RUTA_EVENTO]') AND type in (N'P', N'PC'))
	DROP PROCEDURE [dbo].[PG_CB_KIT_RUTA_EVENTO]
GO

/*
	EXEC	[dbo].[PG_CB_KIT_RUTA_EVENTO] 0,0,	 1
*/
CREATE PROCEDURE [dbo].[PG_CB_KIT_RUTA_EVENTO]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO				INT,
	--============================
	@PP_TODOS					INT
AS

	DECLARE @VP_TA_CATALOGO	AS TABLE
				(	TA_K_CATALOGO		INT,
					TA_D_CATALOGO		VARCHAR(50))

	INSERT INTO @VP_TA_CATALOGO 
	SELECT	K_KIT_RUTA_EVENTO	AS TA_D_CATALOGO,
			D_KIT_RUTA_EVENTO	AS TA_D_CATALOGO
	FROM [DATA_02].[dbo].KIT_RUTA_EVENTO 

	IF @PP_TODOS = 1
		INSERT INTO @VP_TA_CATALOGO VALUES (-1, '( TODOS )'	)

	-- ///////////////////////////////////////////////////
	SELECT	TA_K_CATALOGO	AS K_COMBOBOX,
				TA_D_CATALOGO	AS D_COMBOBOX 
		FROM	@VP_TA_CATALOGO
		ORDER BY  TA_K_CATALOGO 

	-- ==========================================
		
	-- ////////////////////////////////////////////////////
GO


